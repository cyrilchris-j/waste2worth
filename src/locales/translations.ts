const LANGUAGE_STORAGE_KEY = 'waste2worth:language';

export function getStoredLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved && saved in translations) {
      return saved as Language;
    }
  } catch {
    // fallback
  }
  return 'en';
}

export function setStoredLanguage(lang: Language): void {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // ignore
  }
}

export function t(key: string, lang?: Language): string {
  const targetLang = lang || getStoredLanguage();
  return translations[targetLang]?.[key] || translations.en[key] || key;
}

export function localizedSafetyGuides(language: Language): SafetyGuide[] {
  return safetyGuides.map((guide, index) => ({
    ...guide,
    ...(safetyTranslations[language]?.[index] ?? safetyTranslations.en[index]),
  }));
}
